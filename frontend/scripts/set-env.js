/**
 * Set-Env Script for Garagix Frontend
 * Reads frontend/.env (and process.env overrides) and generates strongly-typed
 * src/environments/environment.ts and src/environments/environment.prod.ts.
 * Runs automatically prior to 'npm start', 'npm run build', or manually via 'npm run config:env'.
 */

const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const envPath = path.resolve(rootDir, '.env');
const environmentsDir = path.resolve(rootDir, 'src', 'environments');
const targetPath = path.resolve(environmentsDir, 'environment.ts');
const targetProdPath = path.resolve(environmentsDir, 'environment.prod.ts');

// Helper to parse key-value lines from a .env file
function parseEnvFile(filePath) {
  const envObj = {};
  if (!fs.existsSync(filePath)) {
    return envObj;
  }

  const content = fs.readFileSync(filePath, 'utf8');
  const lines = content.split('\n');

  for (const line of lines) {
    const trimmed = line.trim();
    // Skip empty lines and comments
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.substring(0, eqIdx).trim();
      let val = trimmed.substring(eqIdx + 1).trim();
      // Remove surrounding quotes if present
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.substring(1, val.length - 1);
      }
      envObj[key] = val;
    }
  }

  return envObj;
}

const fileEnv = parseEnvFile(envPath);

// Function to resolve an env variable with fallback: process.env -> fileEnv -> default
function getVar(key, defaultValue) {
  if (process.env[key] !== undefined && process.env[key] !== '') {
    return process.env[key];
  }
  if (fileEnv[key] !== undefined && fileEnv[key] !== '') {
    return fileEnv[key];
  }
  return defaultValue;
}

const isProduction = getVar('NG_APP_PRODUCTION', 'false') === 'true' || process.env.NODE_ENV === 'production';

const config = {
  production: isProduction,
  env: getVar('NG_APP_ENV', 'development'),
  apiUrl: getVar('NG_APP_API_URL', 'http://localhost:5203/api'),
  appName: getVar('NG_APP_NAME', 'Garagix Auto Care'),
  appTagline: getVar('NG_APP_TAGLINE', 'Precision Auto Care & Workshop Management'),
  appVersion: getVar('NG_APP_VERSION', '1.0.0'),
  supportEmail: getVar('NG_APP_SUPPORT_EMAIL', 'support@garagix.lk'),
  supportPhone: getVar('NG_APP_SUPPORT_PHONE', '+94 11 234 5678'),
  workshopAddress: getVar('NG_APP_WORKSHOP_ADDRESS', 'No. 45/A, Nawala Road, Nugegoda, Colombo, Sri Lanka'),
  storagePrefix: getVar('NG_APP_STORAGE_PREFIX', 'garagix_'),
  tokenKey: getVar('NG_APP_TOKEN_KEY', 'garagix_auth_token'),
  userKey: getVar('NG_APP_USER_KEY', 'garagix_auth_user')
};

// Generate TypeScript Environment File content
function generateEnvContent(cfg, isProd) {
  const finalCfg = { ...cfg, production: isProd };
  return `// Auto-generated from frontend/.env by scripts/set-env.js
// Do not edit this file directly; update frontend/.env and run 'npm run config:env'

export interface Environment {
  production: boolean;
  env: string;
  apiUrl: string;
  appName: string;
  appTagline: string;
  appVersion: string;
  supportEmail: string;
  supportPhone: string;
  workshopAddress: string;
  storagePrefix: string;
  tokenKey: string;
  userKey: string;
}

export const environment: Environment = {
  production: ${finalCfg.production},
  env: '${finalCfg.env}',
  apiUrl: '${finalCfg.apiUrl}',
  appName: '${finalCfg.appName}',
  appTagline: '${finalCfg.appTagline}',
  appVersion: '${finalCfg.appVersion}',
  supportEmail: '${finalCfg.supportEmail}',
  supportPhone: '${finalCfg.supportPhone}',
  workshopAddress: '${finalCfg.workshopAddress}',
  storagePrefix: '${finalCfg.storagePrefix}',
  tokenKey: '${finalCfg.tokenKey}',
  userKey: '${finalCfg.userKey}'
};
`;
}

// Ensure target directory exists
if (!fs.existsSync(environmentsDir)) {
  fs.mkdirSync(environmentsDir, { recursive: true });
}

// Write environment.ts
fs.writeFileSync(targetPath, generateEnvContent(config, false), 'utf8');

// Write environment.prod.ts
fs.writeFileSync(targetProdPath, generateEnvContent(config, true), 'utf8');

console.log('\x1b[32m%s\x1b[0m', '✔ Generated frontend environments from .env:');
console.log(`  ➜ Target: ${targetPath}`);
console.log(`  ➜ API Base URL: ${config.apiUrl}`);
console.log(`  ➜ App: ${config.appName} (v${config.appVersion})`);

